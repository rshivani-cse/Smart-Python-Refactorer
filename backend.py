
from pathlib import Path
from uuid import uuid4
import shutil
import ast

from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles

from refactorer import main as run_agent

app = FastAPI(title="Smart Python Refactorer API")


BASE_DIR = Path(__file__).resolve().parent
UPLOADS_DIR = BASE_DIR / "uploads"
UPLOADS_DIR.mkdir(parents=True, exist_ok=True)
MAX_UPLOAD_SIZE = 1 * 1024 * 1024  # 1 MB

# Serve frontend CSS and JavaScript files
app.mount(
    "/static",
    StaticFiles(directory=BASE_DIR / "static"),
    name="static"
)


@app.get("/")
def home():
    return {
        "message": "Smart Python Refactorer API is running."
    }


# Serve the frontend website
@app.get("/app")
def frontend():
    return FileResponse(BASE_DIR / "static" / "index.html")


@app.post("/refactor")
async def refactor_file(file: UploadFile = File(...)):
    if not file.filename or Path(file.filename).suffix.lower() != ".py":
        raise HTTPException(
            status_code=400,
            detail="Please upload a Python (.py) file."
        )


    # Create a separate directory for this request.
    job_id = uuid4().hex
    job_dir = UPLOADS_DIR / job_id
    job_dir.mkdir(parents=True)

    # Use a fixed safe filename instead of trusting the uploaded path.
    input_path = job_dir / "input.py"
    original_filename = Path(file.filename.replace("\\", "/")).name
    original_stem = Path(original_filename).stem
    (job_dir / "original_stem.txt").write_text(
        original_stem,
        encoding="utf-8"
    )

    try:
        content = await file.read(MAX_UPLOAD_SIZE + 1)
        if not content:
            raise HTTPException(
                status_code=400,
                detail="The uploaded file is empty."
            )
        if len(content) > MAX_UPLOAD_SIZE:
            raise HTTPException(
                status_code=413,
                detail="File too large. Maximum upload size is 1 MB."
            )

        input_path.write_bytes(content)
        try:
            ast.parse(content.decode("utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            raise HTTPException(
                status_code=400,
                detail="The uploaded file must contain valid UTF-8 Python code."
            )

        # Run the existing agent on the uploaded file.
        result = run_agent(str(input_path))

        return {
            "job_id": job_id,
            "result": result,
            "download_url": (
                f"/download/{job_id}"
                if result.get("status") in ("success", "no_changes_needed")
                else None
            )
        }

    except HTTPException:
        shutil.rmtree(job_dir, ignore_errors=True)
        raise

    except Exception:
        shutil.rmtree(job_dir, ignore_errors=True)
        raise HTTPException(
            status_code=500,
            detail="Refactoring failed due to an internal error. Please try again."
        ) from None

    finally:
        await file.close()



@app.get("/download/{job_id}")
def download_file(job_id: str):
    # Accept only UUIDs in the format generated by this backend.
    if len(job_id) != 32 or any(
        char not in "0123456789abcdef" for char in job_id
    ):
        raise HTTPException(status_code=404, detail="File not found.")

    job_dir = UPLOADS_DIR / job_id
    output_path = job_dir / "input.py"
    name_path = job_dir / "original_stem.txt"

    if not output_path.is_file() or not name_path.is_file():
        raise HTTPException(status_code=404, detail="File not found.")

    original_stem = name_path.read_text(encoding="utf-8").strip()

    return FileResponse(
        path=output_path,
        media_type="text/x-python",
        filename=f"{original_stem}_refactored.py"
    )
